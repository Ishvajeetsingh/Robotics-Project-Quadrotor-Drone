"""
simulate_mission.py
===================
Standalone Python flight-dynamics simulator for the Mavic 2 Pro survey mission.

This module provides a physics approximation that runs entirely without Webots,
making it possible to:
    - Generate realistic-looking flight logs for both 'baseline' and 'tuned' gains
    - Run the complete analysis and plotting pipeline
    - Test all unit tests
    - Compare controller performance quantitatively

Physics model:
    - Simplified point-mass model with drag and first-order motor lag
    - Altitude controlled by vertical thrust PID
    - Horizontal position controlled by attitude → force decomposition
    - Attitude modelled as first-order lag on commanded angle
    - Wind disturbance optional (disabled by default for reproducibility)

This is NOT the Webots simulation. It is a self-contained approximation used
to demonstrate controller logic and generate sample data.

All data generated by this script is clearly labelled as SIMULATED (standalone)
not WEBOTS simulation data. Real Webots runs will differ in detail.
"""

from __future__ import annotations

import math
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

_PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_PROJECT_ROOT))

from config.config_loader import ConfigLoader
from control.flight_controller import FlightController, DroneState
from navigation.waypoint_manager import WaypointManager, MissionPhase
from simulation.data_logger import DataLogger


# ---------------------------------------------------------------------------
# Physics parameters (tuned to approximate real DJI Mavic 2 Pro dynamics)
# ---------------------------------------------------------------------------
MASS_KG: float = 0.907          # DJI Mavic 2 Pro mass ~907 g
GRAVITY: float = 9.81            # m/s²
DRAG_XZ: float = 0.35            # horizontal drag coefficient
DRAG_Y: float  = 0.45            # vertical drag coefficient
ATTITUDE_TAU: float = 0.15       # attitude first-order time constant (s)
# Thrust-to-force conversion:  each unit of base_thrust ≈ K_THRUST N/unit
K_THRUST: float = MASS_KG * GRAVITY / 68.5   # hover at base_thrust=68.5


@dataclass
class PhysicsState:
    """Full integrator state for the simplified drone dynamics."""
    t:    float = 0.0
    x:    float = 0.0   # East (m)
    y:    float = 0.0   # Altitude (m)
    z:    float = 0.0   # South (m)
    vx:   float = 0.0
    vy:   float = 0.0
    vz:   float = 0.0
    roll:  float = 0.0
    pitch: float = 0.0
    yaw:   float = 0.0


def _clamp(v: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, v))


class StandaloneSimulator:
    """
    Runs the full mission loop without Webots and saves a CSV log.

    Parameters
    ----------
    experiment  : 'baseline' or 'tuned'
    config_path : Optional path to mission.yaml
    verbose     : Print progress every N simulated seconds
    """

    def __init__(
        self,
        experiment: str = "baseline",
        config_path: Optional[Path] = None,
        verbose: bool = True,
    ) -> None:
        self._experiment = experiment
        self._verbose = verbose

        cfg_path = config_path or (_PROJECT_ROOT / "config" / "mission.yaml")
        self._cfg = ConfigLoader(cfg_path)

        gains  = self._cfg.controller_gains(experiment)
        dt_s   = self._cfg.timestep_ms / 1000.0
        self._dt = dt_s
        self._controller = FlightController(gains=gains, dt_s=dt_s)

        self._wp_manager = WaypointManager(
            waypoints=self._cfg.waypoints,
            target_altitude_m=self._cfg.target_altitude_m,
            arrival_radius_m=self._cfg.arrival_radius_m,
            dwell_time_s=self._cfg.dwell_time_s,
        )

        log_dir  = _PROJECT_ROOT / self._cfg.log_dir / f"experiment_{experiment}"
        log_dir.mkdir(parents=True, exist_ok=True)
        log_name = f"flight_log_{experiment}.csv"
        self._logger = DataLogger(
            output_path=log_dir / log_name,
            fields=self._cfg.log_fields,
        )
        self._log_path = log_dir / log_name

        self._phys = PhysicsState()
        self._max_time = self._cfg.max_mission_time_s

        print(f"\n{'='*60}")
        print(f"  Standalone Simulator  –  experiment='{experiment}'")
        print(f"  Controller : {gains.get('name', experiment)}")
        print(f"  Timestep   : {dt_s*1000:.0f} ms")
        print(f"  Max time   : {self._max_time} s")
        print(f"  Log file   : {log_dir / log_name}")
        print(f"{'='*60}\n")

    # ------------------------------------------------------------------
    # Integration step
    # ------------------------------------------------------------------

    def _integrate(
        self,
        phys: PhysicsState,
        desired_roll: float,
        desired_pitch: float,
        thrust_total: float,
    ) -> PhysicsState:
        """
        Euler-integrate drone dynamics for one timestep.

        Attitude is modelled as first-order lag; position via Newton's second law.
        """
        dt = self._dt

        # ---- Attitude (first-order lag toward commanded angle) ----------
        alpha = dt / (ATTITUDE_TAU + dt)
        new_roll  = phys.roll  + alpha * (desired_roll  - phys.roll)
        new_pitch = phys.pitch + alpha * (desired_pitch - phys.pitch)
        new_yaw   = phys.yaw   # yaw held at 0 (no yaw command in this demo)

        # ---- Forces in world frame -------------------------------------
        # Total thrust (N) from all four motors
        f_thrust = thrust_total * K_THRUST * 4  # four motors combined

        # Decompose thrust through attitude angles
        fy = f_thrust * math.cos(new_roll) * math.cos(new_pitch)  # up
        fx = f_thrust * math.sin(new_pitch)                         # East
        fz = -f_thrust * math.sin(new_roll)                         # South

        # Net vertical force (subtract gravity)
        net_fy = fy - MASS_KG * GRAVITY

        # Drag (proportional to velocity)
        drag_x = -DRAG_XZ * phys.vx
        drag_y = -DRAG_Y  * phys.vy
        drag_z = -DRAG_XZ * phys.vz

        # Accelerations
        ax = (fx + drag_x) / MASS_KG
        ay = (net_fy + drag_y) / MASS_KG
        az = (fz + drag_z) / MASS_KG

        # ---- Integrate velocities & positions --------------------------
        new_vx = phys.vx + ax * dt
        new_vy = phys.vy + ay * dt
        new_vz = phys.vz + az * dt

        new_x = phys.x + phys.vx * dt
        new_y = max(0.0, phys.y + phys.vy * dt)   # can't go below ground
        new_z = phys.z + phys.vz * dt

        return PhysicsState(
            t=phys.t + dt,
            x=new_x, y=new_y, z=new_z,
            vx=new_vx, vy=new_vy, vz=new_vz,
            roll=new_roll, pitch=new_pitch, yaw=new_yaw,
        )

    # ------------------------------------------------------------------
    # Main loop
    # ------------------------------------------------------------------

    def run(self) -> Path:
        """Run the full mission and return the path to the log CSV."""
        step_count = 0
        last_report_t = 0.0

        with self._logger:
            while self._phys.t < self._max_time:
                t = self._phys.t

                # ---- Convert physics state to DroneState ---------------
                state = DroneState(
                    time_s=t,
                    x=self._phys.x,
                    y=self._phys.y,
                    z=self._phys.z,
                    roll=self._phys.roll,
                    pitch=self._phys.pitch,
                    yaw=self._phys.yaw,
                    vx=self._phys.vx,
                    vy=self._phys.vy,
                    vz=self._phys.vz,
                )

                # ---- Mission state machine -----------------------------
                phase = self._wp_manager.update(
                    drone_x=state.x,
                    drone_z=state.z,
                    drone_y=state.y,
                    current_time_s=t,
                )

                target_x = self._wp_manager.target_x
                target_z = self._wp_manager.target_z
                target_y = self._wp_manager.target_y
                wp_id    = self._wp_manager.current_waypoint_index

                # ---- PID control --------------------------------------
                commands, diag = self._controller.compute(
                    state=state,
                    target_x=target_x,
                    target_y=target_y,
                    target_z=target_z,
                )

                # ---- Log data ----------------------------------------
                self._logger.log_step(
                    time_s=t,
                    waypoint_id=wp_id,
                    desired_x=target_x,
                    desired_y=target_y,
                    desired_z=target_z,
                    actual_x=state.x,
                    actual_y=state.y,
                    actual_z=state.z,
                    roll=state.roll,
                    pitch=state.pitch,
                    yaw=state.yaw,
                    motor_fl=commands.fl,
                    motor_fr=commands.fr,
                    motor_rl=commands.rl,
                    motor_rr=commands.rr,
                )

                # ---- Integrate physics --------------------------------
                # Use the average of all four motor commands as total thrust
                avg_thrust = (commands.fl + commands.fr +
                              commands.rl + commands.rr) / 4.0

                self._phys = self._integrate(
                    phys=self._phys,
                    desired_roll=diag['desired_roll'],
                    desired_pitch=diag['desired_pitch'],
                    thrust_total=avg_thrust,
                )

                step_count += 1

                # ---- Progress reporting -------------------------------
                if self._verbose and (t - last_report_t) >= 5.0:
                    last_report_t = t
                    print(
                        f"  t={t:7.2f}s  Phase={phase.name:12s}  "
                        f"WP={wp_id}  "
                        f"Pos=({state.x:5.2f},{state.y:5.2f},{state.z:5.2f})  "
                        f"Target=({target_x:.1f},{target_y:.1f},{target_z:.1f})  "
                        f"Reached={self._wp_manager.waypoints_reached}"
                    )

                # ---- Mission complete --------------------------------
                if phase == MissionPhase.COMPLETE:
                    print(
                        f"\n  Mission COMPLETE at t={t:.2f} s  "
                        f"({self._wp_manager.waypoints_reached}/"
                        f"{self._wp_manager.total_waypoints} waypoints)\n"
                    )
                    break

        print(f"  Log rows : {self._logger.row_count}")
        print(f"  Log saved: {self._log_path}\n")
        return self._log_path


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------

if __name__ == '__main__':
    import argparse

    parser = argparse.ArgumentParser(
        description="Standalone drone simulator (no Webots required)"
    )
    parser.add_argument(
        '--experiment',
        choices=['baseline', 'tuned', 'both'],
        default='both',
        help="Which controller gains to simulate (default: both)",
    )
    args = parser.parse_args()

    experiments = (
        ['baseline', 'tuned'] if args.experiment == 'both'
        else [args.experiment]
    )

    for exp in experiments:
        sim = StandaloneSimulator(experiment=exp)
        sim.run()

    print("Done. Run 'python scripts/run_analysis.py' to generate graphs.")
